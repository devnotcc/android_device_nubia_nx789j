#!/usr/bin/env python3
# Generates the NubiaParts thermal profiles from the stock /vendor/etc/thermal-engine.conf
# (stock.conf). Only the skin-temperature CPU and GPU throttling thresholds move; the
# frequency caps, the battery charging control and every other rule stay as stock.
import re

PROFILES = {
    # name: (cpu thresholds, cpu clear, gpu thresholds, gpu clear), in milli-degC
    'performance': ([47, 49, 51, 53, 55, 57], [46, 47, 49, 51, 53, 55],
                    [50, 52, 54, 56], [48, 50, 52, 54]),
    'extreme':     ([52, 54, 56, 58, 60, 62], [51, 52, 54, 56, 58, 60],
                    [54, 56, 58, 60], [52, 54, 56, 58]),
    'ultra':       ([60, 61, 62, 63, 64, 65], [59, 60, 61, 62, 63, 64],
                    [60, 62, 64, 65], [59, 60, 62, 64]),
}

stock = open('stock.conf').read()

def section(text, name, thr, clr):
    m = re.search(r'\[' + name + r'\].*?(?=\n\[|\Z)', text, re.S)
    body = m.group(0)
    fmt = lambda v: '  '.join(str(x * 1000) for x in v)
    body = re.sub(r'^thresholds\s.*$', 'thresholds       ' + fmt(thr), body, flags=re.M)
    body = re.sub(r'^thresholds_clr\s.*$', 'thresholds_clr   ' + fmt(clr), body, flags=re.M)
    return text[:m.start()] + body + text[m.end():]

for name, (ct, cc, gt, gc) in PROFILES.items():
    out = section(stock, 'SKIN_CPU_MONITOR', ct, cc)
    out = section(out, 'SKIN_GPU_MONITOR', gt, gc)
    out = '# NubiaParts "%s" thermal profile, generated by gen.py from stock.conf\n' % name + out
    open('thermal-engine-%s.conf' % name, 'w', newline='\n').write(out)
    print(name, 'ok')
